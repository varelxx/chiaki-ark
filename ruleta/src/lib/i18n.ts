export type ClaveTexto = keyof typeof es;
const textos: Record<Idioma, typeof es> = { es, en };

export function t(idioma: Idioma, clave: ClaveTexto, vars: Record<string, string | number> = {}): string {
  return textos[idioma][clave].replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export function elegirIdioma(param: string | undefined, acceptLanguage: string | undefined | null, porDefecto: Idioma = "es"): Idioma {
  if (param === "es" || param === "en") return param;
  if (acceptLanguage) {
    const primero = acceptLanguage.split(",")[0]?.trim().toLowerCase() ?? "";
    if (primero.startsWith("es")) return "es";
    if (primero) return "en";
  }
  return porDefecto;
}

export const nombreSegun = (idioma: Idioma, o: { nombre: string | null; nombre_en: string | null }): string =>
  (idioma === "en" ? o.nombre_en || o.nombre : o.nombre || o.nombre_en) ?? "";
